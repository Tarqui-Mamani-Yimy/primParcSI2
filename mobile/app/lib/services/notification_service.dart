import 'package:flutter/foundation.dart';
import 'package:flutter_local_notifications/flutter_local_notifications.dart';
import 'package:flutter_timezone/flutter_timezone.dart';
import 'package:timezone/data/latest_all.dart' as tzdata;
import 'package:timezone/timezone.dart' as tz;

/// Port for local notifications, so the rules can be tested with a fake.
abstract class AppNotifier {
  /// Shows a notification right now.
  Future<void> show(int id, String title, String body);

  /// Schedules a notification handled by Android itself: it fires even if
  /// the app is closed. Dates in the past are ignored.
  Future<void> schedule(int id, DateTime at, String title, String body);

  Future<void> cancel(int id);

  Future<void> cancelAll();
}

/// Used where no device notifications are available (tests, guest mode).
class NoopNotifier implements AppNotifier {
  const NoopNotifier();

  @override
  Future<void> show(int id, String title, String body) async {}

  @override
  Future<void> schedule(int id, DateTime at, String title, String body) async {}

  @override
  Future<void> cancel(int id) async {}

  @override
  Future<void> cancelAll() async {}
}

/// Local notifications generated by the phone (`flutter_local_notifications`).
/// They are not server push: the app decides when to show them, using the
/// data it already syncs from the backend. Every failure is swallowed so a
/// notification problem never breaks a purchase or a sync.
class LocalNotificationService implements AppNotifier {
  LocalNotificationService._();

  static final LocalNotificationService instance = LocalNotificationService._();

  static const _fallbackTimezone = 'America/La_Paz';
  static const _details = NotificationDetails(
    android: AndroidNotificationDetails(
      'voguely_general',
      'Voguely',
      channelDescription: 'Recordatorios y novedades de tus compras',
      importance: Importance.high,
      priority: Priority.high,
    ),
  );

  final FlutterLocalNotificationsPlugin _plugin =
      FlutterLocalNotificationsPlugin();
  bool _ready = false;

  Future<void> init() async {
    if (_ready) return;
    try {
      tzdata.initializeTimeZones();
      try {
        final info = await FlutterTimezone.getLocalTimezone();
        tz.setLocalLocation(tz.getLocation(info.identifier));
      } catch (_) {
        tz.setLocalLocation(tz.getLocation(_fallbackTimezone));
      }
      await _plugin.initialize(
        settings: const InitializationSettings(
          android: AndroidInitializationSettings('@mipmap/ic_launcher'),
        ),
      );
      _ready = true;
    } catch (error) {
      debugPrint('Local notifications unavailable: $error');
    }
  }

  /// Android 13+ asks the user once; older versions grant it on install.
  Future<void> requestPermission() async {
    if (!_ready) return;
    try {
      await _plugin
          .resolvePlatformSpecificImplementation<
              AndroidFlutterLocalNotificationsPlugin>()
          ?.requestNotificationsPermission();
    } catch (_) {}
  }

  @override
  Future<void> show(int id, String title, String body) async {
    if (!_ready) return;
    try {
      await _plugin.show(
          id: id, title: title, body: body, notificationDetails: _details);
    } catch (_) {}
  }

  @override
  Future<void> schedule(int id, DateTime at, String title, String body) async {
    if (!_ready || !at.isAfter(DateTime.now())) return;
    try {
      await _plugin.zonedSchedule(
        id: id,
        scheduledDate: tz.TZDateTime.from(at, tz.local),
        notificationDetails: _details,
        // Inexact: no SCHEDULE_EXACT_ALARM permission needed; Android may
        // deliver it a few minutes late to save battery.
        androidScheduleMode: AndroidScheduleMode.inexactAllowWhileIdle,
        title: title,
        body: body,
      );
    } catch (_) {}
  }

  @override
  Future<void> cancel(int id) async {
    if (!_ready) return;
    try {
      await _plugin.cancel(id: id);
    } catch (_) {}
  }

  @override
  Future<void> cancelAll() async {
    if (!_ready) return;
    try {
      await _plugin.cancelAll();
    } catch (_) {}
  }
}
